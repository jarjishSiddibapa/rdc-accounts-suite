-- Untagged Invoices Report Generator: bring the Location Name and Accounts
-- Incharge mapping tables up to date (25 location names and 7 incharges added
-- after the original seed, plus the BANGALORE / MANGALORE incharge change).
--
-- Safe to run repeatedly, before or after the application has first started:
--   * the tables are created if missing (same definition the app uses);
--   * rows are only INSERTED when their key is absent - existing rows, edits
--     made in the application and archived (soft-deleted) rows are never
--     overwritten or revived;
--   * the two BANGALORE / MANGALORE incharge changes apply only while the row
--     still holds the original seed value ('Elairaja').
-- It is the full current mapping set rather than just the delta, so a database
-- where these tables are still empty gets the complete data and the
-- application's own first-use seeding (which only runs on an empty table) is
-- not left half-populated.
-- If production uses a database name other than `rdc_accounts_suite`, change
-- the USE statement first.

